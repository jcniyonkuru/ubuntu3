  let CURRENT_LANG = 'fr';

  function detectBrowserLang() {
    const langs = (navigator.languages || [navigator.language || 'fr'])
      .map((l) => String(l).toLowerCase().split('-')[0]);
    for (const l of langs) if (SUPPORTED.indexOf(l) !== -1) return l;
    return 'fr';
  }

  function setLang(lang) {
    if (SUPPORTED.indexOf(lang) === -1) return;
    CURRENT_LANG = lang;
    document.documentElement.setAttribute('lang', lang);
  }

  function getLang() { return CURRENT_LANG; }

  function t(key, vars) {
    let s = (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]);
    if (s == null) s = (I18N.fr && I18N.fr[key]);
    if (s == null) s = key;
    if (vars) {
      for (const k in vars) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      }
    }
    return s;
  }

  function tn(n, singularKey, pluralKey, vars) {
    const key = n === 1 ? singularKey : pluralKey;
    const merged = Object.assign({ n }, vars || {});
    return t(key, merged);
  }

  function languages() {
    return SUPPORTED.map((code) => ({ code, label: LABELS[code] }));
  }

  function dateLocale() {
    if (CURRENT_LANG === 'rn') return 'rn-BI';
    if (CURRENT_LANG === 'en') return 'en';
    return 'fr-FR';
  }

  window.I18N = { t, tn, setLang, getLang, detectBrowserLang, languages, dateLocale };
